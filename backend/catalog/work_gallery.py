def create_work_gallery(WorkCategory, WorkItem, WorkItemImage):
    for spec in CATEGORIES:
        category = WorkCategory.objects.create(
            name=spec["name"],
            slug=spec["slug"],
            description=spec["description"],
            order=spec["order"],
            is_published=True,
        )
        for item_spec in spec["items"]:
            item = WorkItem.objects.create(
                category=category,
                title=item_spec["title"],
                slug=item_spec["slug"],
                summary=item_spec["summary"],
                description=item_spec["description"],
                image_url=item_spec["image_url"],
                order=item_spec["order"],
                is_published=True,
            )
            for url, caption, order in item_spec["images"]:
                WorkItemImage.objects.create(
                    item=item,
                    image_url=url,
                    caption=caption,
                    order=order,
                    is_published=True,
                )
